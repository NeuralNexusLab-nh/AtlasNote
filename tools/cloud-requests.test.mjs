import assert from 'node:assert/strict';
import {RequestQueue} from '../script/cloud-requests.js';
let checks=0;const ok=(value,message)=>{assert.ok(value,message);checks++;};
const simulated=(options={})=>{let clock=0;return new RequestQueue({now:()=>clock,wait:async ms=>{clock+=ms;},...options});};
let active=0,peak=0;const bounded=simulated();
await Promise.all(Array.from({length:20},()=>bounded.run(async()=>{active++;peak=Math.max(peak,active);await new Promise(resolve=>setImmediate(resolve));active--;return true;})));
ok(peak===2,'No more than two SDK calls execute at once');
const retry=simulated(),attempts=[];
const value=await retry.run(()=>{attempts.push(retry.now());if(attempts.length<3)throw {status:429,code:'too_many_requests'};return 'saved';});
ok(value==='saved'&&attempts.length===3,'Transient rate limits retry at most three times');
ok(attempts[1]-attempts[0]>=1000&&attempts[2]-attempts[1]>=2000,'429 retries wait with increasing backoff');
let failures=0;await assert.rejects(()=>retry.run(()=>{failures++;throw {status:429};}));
ok(failures===3&&retry.pending.length===0,'Persistent throttling terminates without an endless request loop');
let denied=0;await assert.rejects(()=>retry.run(()=>{denied++;throw {status:402};}));
ok(denied===1,'Nonretryable quota errors are not repeatedly submitted');
const writes=simulated(),starts=[];for(let i=0;i<4;i++)await writes.run(()=>starts.push(writes.now()),'write');
ok(starts.slice(1).every((time,index)=>time-starts[index]>=650),'Writes are paced below the Free write quota');
const rolling=simulated({gap:0}),times=[];for(let i=0;i<241;i++)await rolling.run(()=>times.push(rolling.now()));
ok(times[240]-times[0]>=60000,'The rolling read budget pauses before exceeding the minute quota');
const explicit=simulated(),explicitStarts=[];let explicitTry=0;await explicit.run(()=>{explicitStarts.push(explicit.now());if(!explicitTry++)throw {status:429,retry_after:3};return true;});
ok(explicitStarts[1]-explicitStarts[0]>=3000,'Provider retry_after is honored');
console.log('PASS '+checks+' SDK queue and backoff checks.');
